def mm_to_inches(mm):
    """
    convert millimetres to inches.
    
    Args:
    float: Meaasurements in inches.
    """
    return mm/ 25.4

def inches_to_mm(inches):
    """
    convert inches to millimetres.

    Args:
    inches(float): Meaurement in inches.
Returns:
    float: Measurement in millimetres.
    """
    return inches * 25.4